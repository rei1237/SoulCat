import fs from 'node:fs';
import ts from 'typescript';
import { createHash } from 'node:crypto';
const sourcePath = 'D:/Development/code-destiny/js/saju-engine.js';
const source = fs.readFileSync(sourcePath, 'utf8');
const ast = ts.createSourceFile(sourcePath, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS);
const declarations = new Map();
for (const node of ast.statements) {
  if (ts.isFunctionDeclaration(node) && node.name) declarations.set(node.name.text, node.getText(ast));
  if (ts.isVariableStatement(node)) for (const d of node.declarationList.declarations)
    if (ts.isIdentifier(d.name)) declarations.set(d.name.text, `var ${d.getText(ast)};`);
}
const roots = ['_applyTrueSolarTimeCorrection', '_cdCivilDayPillar', '_cdHourPillarFromDayStem', 'calcPower', 'calcNatalElement', 'analyzeJohu', 'detectJong', 'applyRuntimeYongshinPolicy', 'resolveBirthTimezoneOffset'];
const selected = new Map();
function include(name) {
  if (selected.has(name) || !declarations.has(name)) return;
  const code = declarations.get(name); selected.set(name, code);
  const fragment = ts.createSourceFile('fragment.js', code, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS);
  function visit(n) { if (ts.isIdentifier(n) && !(ts.isPropertyAccessExpression(n.parent) && n.parent.name === n)) include(n.text); ts.forEachChild(n, visit); }
  visit(fragment);
}
roots.forEach(include);
if (!process.argv.includes('--write')) { console.log(JSON.stringify({symbols:[...selected.keys()], bytes:[...selected.values()].join('\n').length})); }
else {
  const text = `// Generated by scripts/extract-saju-runtime.mjs; original formulas unchanged.\n${[...selected.values()].join('\n\n')}\nexport { ${roots.join(', ')} };\n`;
  fs.writeFileSync('server/vendor/code-destiny/saju-runtime.js', text);
  fs.writeFileSync('docs/saju-runtime-provenance.json', JSON.stringify({sourcePath, sha256:createHash('sha256').update(source).digest('hex'), symbols:[...selected].map(([name,code])=>({name,sha256:createHash('sha256').update(code).digest('hex')}))},null,2));
  console.log(`Extracted ${selected.size} declarations without formula edits.`);
}
